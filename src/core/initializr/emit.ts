// Emitters: plain templates that turn a scope manifest into files. Each one is a "contributor" in
// the Spring Initializr sense; add a new output by adding an entry to EMITTERS.

import { isInfrastructure } from './resolve.ts';
import { compareVersions } from './semver.ts';
import type { Actor, Manifest, ManifestIg, RegistrySnapshot } from './types.ts';

export interface Emitter {
  id: string;
  label: string;
  filename: string;
  language: 'json' | 'yaml' | 'markdown';
  mediaType: string;
  description: string;
  emit(m: Manifest, reg?: RegistrySnapshot): string;
}

const STRENGTH_LABEL = {
  required: 'Required',
  recommended: 'Recommended',
  optional: 'Optional',
} as const;
const BASIS_LABEL: Record<string, string> = {
  adopted: 'adopted in regulation',
  program: 'named in program rules',
  svap: 'SVAP-approved',
  recommended: 'agency-recommended',
  'enforcement-discretion': 'enforcement discretion',
  'permitted-update': 'permitted updated version',
  proposed: 'proposed rule only',
  profile: 'profile choice',
};

/** Pinned IGs that package tools can actually fetch. */
function installable(m: Manifest, reg?: RegistrySnapshot): ManifestIg[] {
  return m.igs.filter((i) => i.pin && (!reg || reg.packages[i.package]?.inRegistry !== false));
}

function conflictVersions(ig: ManifestIg): string[] {
  const tops = ig.reasons
    .filter((r) => r.strength === 'required' && r.accepts.length)
    .map((r) => r.accepts[0]);
  return [...new Set(tops)].sort((a, b) => compareVersions(b, a));
}

function aliasKey(name: string, version: string): string {
  return `v${version.replace(/[^0-9]/g, '')}@npm:${name}`;
}

function header(m: Manifest, comment: string): string {
  return [
    `${comment} Generated by ${m.tool.name} ${m.tool.version}${m.tool.stage ? ` (${m.tool.stage})` : ''} on ${m.generated.slice(0, 10)} (KB as of ${m.kbAsOf}).`,
    `${comment} Target date ${m.profile.asOf}; drivers ${driverList(m) || 'none'}; actors ${m.profile.actors.join(' + ')}.`,
    `${comment} ${m.disclaimer}`,
  ].join('\n');
}

/** "cms-0057-f@provider (provider-access, prior-auth)": the drivers as the CLI takes them. */
function driverList(m: Manifest): string {
  return m.profile.drivers
    .map(
      (d) =>
        d.id +
        (d.side ? `@${d.side}` : '') +
        (d.components?.length ? ` (${d.components.join(', ')})` : ''),
    )
    .join('; ');
}

function slug(m: Manifest): string {
  return (
    (m.profile.projectName || 'my-fhir-project')
      .toLowerCase()
      .replace(/[^a-z0-9.]+/g, '-')
      .replace(/^-|-$/g, '') || 'my-fhir-project'
  );
}

