const packageJson: Emitter = {
  id: 'package-json',
  label: 'package.json',
  filename: 'package.json',
  language: 'json',
  mediaType: 'application/json',
  description:
    'FHIR NPM package manifest for Firely Terminal, SUSHI-built IGs and other package tools.',
  emit(m, reg) {
    const deps: Record<string, string> = { 'hl7.fhir.r4.core': '4.0.1' };
    for (const ig of installable(m, reg)) deps[ig.package] = ig.pin!;
    for (const ig of m.igs.filter((i) => !i.pin && i.pinNote?.startsWith('Conflict'))) {
      const [first, ...rest] = conflictVersions(ig);
      if (first) deps[ig.package] = first;
      for (const v of rest) deps[aliasKey(ig.package, v)] = v;
    }
    return (
      JSON.stringify(
        {
          name: slug(m).replace(/-/g, '.'),
          version: '0.1.0',
          description: `FHIR scope generated by ${m.tool.name} for ${m.profile.asOf} (KB as of ${m.kbAsOf}). ${m.disclaimer}`,
          fhirVersions: ['4.0.1'],
          dependencies: deps,
        },
        null,
        2,
      ) + '\n'
    );
  },
};

const sushiConfig: Emitter = {
  id: 'sushi-config',
  label: 'sushi-config.yaml',
  filename: 'sushi-config.yaml',
  language: 'yaml',
  mediaType: 'application/yaml',
  description: 'Dependencies block for a SUSHI project (merge into your sushi-config.yaml).',
  emit(m, reg) {
    const lines = [header(m, '#'), '', 'fhirVersion: 4.0.1', 'dependencies:'];
    for (const ig of installable(m, reg)) lines.push(`  ${ig.package}: ${ig.pin}`);
    for (const ig of m.igs.filter((i) => !i.pin && i.pinNote?.startsWith('Conflict'))) {
      const [first, ...rest] = conflictVersions(ig);
      if (first) lines.push(`  ${ig.package}: ${first}  # conflict: see report`);
      for (const v of rest) lines.push(`  ${aliasKey(ig.package, v)}: ${v}  # alias (SUSHI 3.16+)`);
    }
    return lines.join('\n') + '\n';
  },
};

