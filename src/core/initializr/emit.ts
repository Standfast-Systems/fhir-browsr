export const EMITTERS: Emitter[] = [
  report,
  packageJson,
  sushiConfig,
  hapiYaml,
  capabilityStatement,
  infernoPlan,
  manifestJson,
];

export function emitterById(id: string): Emitter | undefined {
  return EMITTERS.find((e) => e.id === id);
}

/** Actors present in a manifest, for UI labels. */
export function actorLabel(a: Actor): string {
  return a === 'server' ? 'Server' : 'Client';
}
